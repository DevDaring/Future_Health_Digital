"""Developer tool: produce the *demo fixture* translations with an LLM, once.

    python scripts/gen_fixture_translations.py /path/to/.env

Writes
  app/fixtures/approved_translations/{lang}.json  (template key -> translated template)
  app/fixtures/phrases/{lang}.json                (patient UI strings + quick replies)
  app/fixtures/red_flags/{lang}.yaml              (red-flag lexicon)

All output is labelled "demo fixture — not clinically validated". In a real deployment
a human medical translator approves every entry. Placeholders like {value} and every
number must survive translation; the script verifies that and retries otherwise.
"""

from __future__ import annotations

import json
import re
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.llm.relay_provider import Endpoint, RelayProvider  # noqa: E402

FIX = ROOT / "app" / "fixtures"
LANGS = {"ar": "Arabic (Modern Standard, Gulf-friendly)", "hi": "Hindi", "ur": "Urdu", "ml": "Malayalam", "bn": "Bengali", "tl": "Tagalog (Filipino)"}


def load_env(path: str) -> dict[str, str]:
    env = {}
    for line in Path(path).read_text().splitlines():
        m = re.match(r"\s*([A-Za-z0-9_]+)\s*=\s*(.*)", line)
        if m:
            env[m.group(1)] = m.group(2).strip().strip('"')
    return env


def flat_templates() -> dict[str, str]:
    t = yaml.safe_load((FIX / "templates.yaml").read_text())
    out = {f"ANY.any.{k}": v for k, v in t["generic"].items()}
    for prog, sevs in t["programs"].items():
        for sev, keys in sevs.items():
            for k, v in keys.items():
                out[f"{prog}.{sev}.{k}"] = v
    return out


def placeholders(s: str) -> list[str]:
    return sorted(re.findall(r"\{[a-z_]+\}", s))


def numbers(s: str) -> list[str]:
    return sorted(re.findall(r"\d+(?:\.\d+)?", s))


SYSTEM = (
    "You are a professional medical translator for a patient-communication service in Abu Dhabi. "
    "Translate the JSON values from English into {lang}. Rules: plain, warm, respectful words a person with "
    "basic literacy understands; keep every placeholder in curly braces EXACTLY as written (e.g. {{value}}); keep every number and "
    "the test names HbA1c, FIT, BI-RADS exactly in Latin script with Western digits; keep 999 as 999; do not add or remove "
    "medical information. Return a JSON object with the same keys."
)


def translate_dict(llm: RelayProvider, lang: str, items: dict[str, str]) -> dict[str, str]:
    schema = {"type": "object", "properties": {k: {"type": "string"} for k in items}}
    out: dict[str, str] = {}
    pending = dict(items)
    for _attempt in range(3):
        if not pending:
            break
        res = llm.complete_json(SYSTEM.format(lang=LANGS[lang]), json.dumps(pending, ensure_ascii=False), schema)
        for k, src in list(pending.items()):
            tr = res.get(k)
            if isinstance(tr, str) and placeholders(tr) == placeholders(src) and numbers(tr) == numbers(src):
                out[k] = tr
                pending.pop(k)
    if pending:
        print(f"[{lang}] could not validate {len(pending)} keys: {list(pending)[:5]}")
    return out


def red_flags(llm: RelayProvider, lang: str) -> dict[str, list[str]]:
    en = yaml.safe_load((FIX / "red_flags" / "en.yaml").read_text())
    schema = {"type": "object", "properties": {k: {"type": "array", "items": {"type": "string"}} for k in en}}
    sys_prompt = (
        f"You build a safety lexicon. For each category give 4-8 short phrases a patient would actually type in {LANGS[lang]} "
        "(native script, plus common romanised spellings where people type in Latin letters) meaning the same as the English examples. "
        "Return JSON with the same keys, each a list of strings."
    )
    return llm.complete_json(sys_prompt, json.dumps(en, ensure_ascii=False), schema)


def run_lang(llm: RelayProvider, lang: str) -> None:
    tmpl = flat_templates()
    keys = list(tmpl)
    out: dict[str, str] = {}
    for i in range(0, len(keys), 8):
        out.update(translate_dict(llm, lang, {k: tmpl[k] for k in keys[i : i + 8]}))
    (FIX / "approved_translations" / f"{lang}.json").write_text(
        json.dumps({"_note": "demo fixture — not clinically validated", **out}, ensure_ascii=False, indent=1)
    )
    phrases = json.loads((FIX / "phrases_en.json").read_text())
    tr_phr = {"ui": translate_dict(llm, lang, phrases["ui"]), "quick": translate_dict(llm, lang, phrases["quick"])}
    (FIX / "phrases" / f"{lang}.json").write_text(json.dumps(tr_phr, ensure_ascii=False, indent=1))
    rf = red_flags(llm, lang)
    (FIX / "red_flags" / f"{lang}.yaml").write_text(
        "# Red-flag lexicon — demo fixture generated by LLM, not clinically validated\n"
        + yaml.safe_dump(rf, allow_unicode=True, sort_keys=False)
    )
    print(f"[{lang}] templates {len(out)}/{len(tmpl)}, ui {len(tr_phr['ui'])}, quick {len(tr_phr['quick'])}")


def main() -> None:
    env = load_env(sys.argv[1])
    quality = [
        Endpoint("nanogpt", env["Nano_GPT_Base_URL"], env["NanoGPT_88_API_Key"], "anthropic/claude-sonnet-5.5"),
        Endpoint("nanogpt2", env["Nano_GPT_Base_URL"], env["NanoGPT_2009_API_KEY"], "anthropic/claude-sonnet-5.5"),
    ]
    llm = RelayProvider(fast=quality, quality=quality, timeout_s=240, max_tokens=8000)
    langs = sys.argv[2:] or list(LANGS)
    (FIX / "approved_translations").mkdir(exist_ok=True)
    (FIX / "phrases").mkdir(exist_ok=True)
    with ThreadPoolExecutor(max_workers=6) as ex:
        list(ex.map(lambda lg: run_lang(llm, lg), langs))


if __name__ == "__main__":
    main()
